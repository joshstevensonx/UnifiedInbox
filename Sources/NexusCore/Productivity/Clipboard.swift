import Foundation

/// What a clipboard entry contains, detected locally (spec §1.3 clipboard-aware, §14.3).
public enum ClipKind: String, Codable, Sendable, CaseIterable {
    case text, url, color, path, image

    public var symbolName: String {
        switch self {
        case .text: return "text.alignleft"
        case .url: return "link"
        case .color: return "paintpalette"
        case .path: return "folder"
        case .image: return "photo"
        }
    }
}

public struct ClipEntry: Codable, Identifiable, Equatable, Sendable {
    public var id: UUID
    public var kind: ClipKind
    /// Text content (or a description for images).
    public var text: String
    /// Small PNG thumbnail for images (kept tiny to bound storage).
    public var imagePNG: Data?
    public var sourceApp: String?
    public var date: Date
    public var isPinned: Bool

    public init(id: UUID = UUID(), kind: ClipKind, text: String, imagePNG: Data? = nil,
                sourceApp: String? = nil, date: Date = Date(), isPinned: Bool = false) {
        self.id = id; self.kind = kind; self.text = text; self.imagePNG = imagePNG
        self.sourceApp = sourceApp; self.date = date; self.isPinned = isPinned
    }
}

public enum ClipClassifier {
    /// Pasteboard types that password managers set to say "don't record this" (nspasteboard.org).
    public static let concealedTypes = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    public static func classify(_ raw: String) -> ClipKind {
        let s = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !s.isEmpty, !s.contains("\n") else { return .text }
        if isHexColor(s) { return .color }
        if let url = URL(string: s), let scheme = url.scheme?.lowercased(),
           ["http", "https", "ftp", "mailto", "ssh"].contains(scheme), s.count > scheme.count + 3 {
            return .url
        }
        if (s.hasPrefix("/") || s.hasPrefix("~/")) && s.count > 1 && !s.contains(" -") { return .path }
        return .text
    }

    /// #RGB, #RRGGBB or #RRGGBBAA.
    public static func isHexColor(_ s: String) -> Bool {
        guard s.hasPrefix("#") else { return false }
        let hex = s.dropFirst()
        return [3, 6, 8].contains(hex.count) && hex.allSatisfy(\.isHexDigit)
    }

    /// RGBA 0…1 for a hex colour string.
    public static func rgba(_ s: String) -> (Double, Double, Double, Double)? {
        guard isHexColor(s) else { return nil }
        var hex = String(s.dropFirst())
        if hex.count == 3 { hex = hex.map { "\($0)\($0)" }.joined() }
        if hex.count == 6 { hex += "FF" }
        guard let v = UInt64(hex, radix: 16) else { return nil }
        return (Double((v >> 24) & 0xFF) / 255, Double((v >> 16) & 0xFF) / 255,
                Double((v >> 8) & 0xFF) / 255, Double(v & 0xFF) / 255)
    }
}

/// Bounded clipboard history: newest first, duplicates move to the top, pinned entries are kept.
public struct ClipHistory: Codable, Equatable, Sendable {
    public static let currentSchema = 1
    public var schemaVersion = currentSchema
    public var entries: [ClipEntry] = []
    public var limit: Int

    public init(limit: Int = 200) { self.limit = limit }

    public mutating func add(_ entry: ClipEntry) {
        if let i = entries.firstIndex(where: { $0.kind == entry.kind && $0.text == entry.text && $0.imagePNG == entry.imagePNG }) {
            var existing = entries.remove(at: i)
            existing.date = entry.date
            existing.sourceApp = entry.sourceApp ?? existing.sourceApp
            entries.insert(existing, at: 0)
        } else {
            entries.insert(entry, at: 0)
        }
        trim()
    }

    public mutating func togglePin(_ id: UUID) {
        guard let i = entries.firstIndex(where: { $0.id == id }) else { return }
        entries[i].isPinned.toggle()
    }

    public mutating func remove(_ id: UUID) { entries.removeAll { $0.id == id } }

    public mutating func clearUnpinned() { entries.removeAll { !$0.isPinned } }

    public func search(_ query: String, kind: ClipKind? = nil) -> [ClipEntry] {
        let q = query.trimmingCharacters(in: .whitespaces)
        return entries.filter { e in
            (kind == nil || e.kind == kind) &&
            (q.isEmpty || e.text.localizedCaseInsensitiveContains(q) || (e.sourceApp?.localizedCaseInsensitiveContains(q) ?? false))
        }
        .sorted { a, b in a.isPinned != b.isPinned ? a.isPinned : a.date > b.date }
    }

    /// Drops the oldest unpinned entries beyond `limit`.
    mutating func trim() {
        var unpinnedSeen = 0
        entries = entries.filter { e in
            if e.isPinned { return true }
            unpinnedSeen += 1
            return unpinnedSeen <= limit
        }
    }
}
